"""Per template x planner summary of the verification runs (the table in docs/14 §10.2).

    uv run campus_verification/summarize.py            # prints a markdown table

Uses the verify.py CSVs in campus_verification/data/. For blind_corner, plaza_dense and gauntlet only the
final_* runs count (generated by the final generator); corridor_counterflow, door_exit and intersection come from
the matrix_* runs (their scenarios didn't change afterwards). Episodes with reset_jump > 1.5 m (pedestrians thrown
at the reset, docs/14 §12) are excluded from the pedestrian columns.
"""
from pathlib import Path

import pandas as pd

D = Path(__file__).resolve().parent / "data"
FINAL = ("blind_corner", "plaza_dense", "gauntlet")


def load():
    rows = []
    for f, final in [("matrix_dwb.csv", False), ("matrix_dsrnn.csv", False), ("final_dwb.csv", True),
                     ("final_dsrnn.csv", True)]:
        if (D / f).is_file():
            d = pd.read_csv(D / f)
            d["tmpl"] = d["scenario"].str.replace(r"_s\d+\.json", "", regex=True)
            rows.append(d[d["tmpl"].isin(FINAL) == final])
    d = pd.concat(rows, ignore_index=True)
    d = d[d["outcome"] != "running"]
    # one episode per (scenario, planner): the one with the smallest reset jump (an un-primed duplicate is dropped)
    return d.sort_values("reset_jump").drop_duplicates(["scenario", "planner"]).reset_index(drop=True)


def main():
    d = load()
    d["ok"] = d["reset_jump"] <= 1.5
    out = []
    for (t, p), g in d.groupby(["tmpl", "planner"]):
        h = g[g["ok"]] if g["ok"].any() else g
        out.append({"template": t, "planner": p, "episodes": len(g),
                    "success": f"{int(g['success'].sum())}/{len(g)}",
                    "time (s, median)": round(g["duration"].median(), 1),
                    "robot-person contacts": int(g["collisions"].sum()),
                    "min clearance (m)": round(g["min_clearance"].min(), 2),
                    "min wall/panel clear. (m)": round(g["min_obstacle_clear"].min(), 2),
                    "freeze (s, median)": round(g["freeze_time"].median(), 1),
                    "ped. inside wall (samples)": int(h["h_inside"].sum()),
                    "ped. overlap share": f"{100 * h['pp_frac'].mean():.0f}%",
                    "ped. overlaps >= 2 s": int(h["pp_long"].sum()),
                    "stuck peds": int(h["stuck"].sum()),
                    "speed / desired": round(h["speed_ratio"].median(), 2),
                    "RTF": round(h["rtf"].median(), 2)})
    t = pd.DataFrame(out)
    print("| " + " | ".join(t.columns) + " |")
    print("|" + "---|" * len(t.columns))
    for _, r in t.iterrows():
        print("| " + " | ".join(str(v) for v in r) + " |")


if __name__ == "__main__":
    main()
